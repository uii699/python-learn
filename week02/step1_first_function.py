# ── 第 1 关：认识函数 ──
# 函数 = 给一段代码起个名字，以后喊名字就能执行它
#
# 对比一下你已经会的：
#   print()   input()   int()   random.randint()   ← 这些都是别人写好的函数
#   现在轮到你自己写一个了！
#
# ─────────────────────────────────

# 第 1 部分：定义（教会电脑一个新动作，但此时还不执行）

def greet():
    print("你好！我是你的第一个函数。")
    print("你喊我的名字，我就会出现。")


# 注意看结构：
#   def          ← 关键字，意思是"我要定义函数了"
#   greet        ← 函数名（你随便起，用英文）
#   ()           ← 括号，先空着，第 2 关教你有用的
#   :            ← 冒号，表示"下面是它的身体"
#   缩进的行     ← 函数的身体（和 while 一样的规矩！）


# 第 2 部分：调用（喊它的名字，它才干活）

print("函数定义好了，但它还没动。")
print("现在喊它：")
greet()
print("再喊一次：")
greet()

# 跑完想一想：
# 1. 为什么"还没动"这句话出现在函数输出之前？
# 2. 喊两次 greet() 就输出两遍——这就是"复用"。
